#!/usr/bin/env python3
"""Generate src/models/tool_io.rs — the TOOL_IO table ported from
engine/src/stirling/models/tool_io.py (itself generated from the Java
OpenAPI spec). Regenerate whenever tool_io.py changes:

    python3 scripts/gen_tool_io.py
"""

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PY_IO = ROOT / "engine/src/stirling/models/tool_io.py"
OUT = ROOT / "rust/engine/src/models/tool_io.rs"


def enum_values(tree, name):
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == name:
            return [
                (t.id, item.value.value)
                for item in node.body
                if isinstance(item, ast.Assign)
                for t in item.targets
                if isinstance(t, ast.Name)
            ]
    raise SystemExit(f"enum {name} not found")


def attr(node):
    """'ToolFormat.PDF' -> 'Pdf'; 'ToolArity.SISO' -> 'Siso'."""
    raw = node.attr
    return "".join(w.capitalize() for w in raw.lower().split("_"))


def member(node):
    return node.attr  # ToolEndpoint.CBR_TO_PDF -> CBR_TO_PDF


def lit(node):
    """Constant string/int/bool or None."""
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Name) and node.id == "None":
        return None
    raise ValueError(f"unsupported literal {ast.dump(node)}")


def when_node(node):
    kw = {k.arg: k.value for k in node.keywords}
    return {
        "param": lit(kw["param"]),
        "matches": [lit(e) for e in kw["matches"].elts],
        "default": lit(kw["default"]) if "default" in kw else None,
    }


def case_node(node):
    kw = {k.arg: k.value for k in node.keywords}
    return {
        "when": [when_node(e) for e in kw["when"].elts] if "when" in kw else [],
        "produces": attr(kw["produces"]),
        "arity": attr(kw["arity"]),
    }


def spec_node(node):
    kw = {k.arg: k.value for k in node.keywords}
    return {
        "accepts": [attr(e) for e in kw["accepts"].elts],
        "produces": attr(kw["produces"]),
        "arity": attr(kw["arity"]),
        "cases": [case_node(e) for e in kw["cases"].elts] if "cases" in kw else [],
    }


def rust_str(s):
    return json.dumps(s)


def main():
    tree = ast.parse(PY_IO.read_text())
    formats = enum_values(tree, "ToolFormat")
    arities = enum_values(tree, "ToolArity")

    # member name -> path from ToolEndpoint? tool_io.py imports it; resolve
    # via tool_models.py like gen_tool_texts does.
    tm = ast.parse((ROOT / "engine/src/stirling/models/tool_models.py").read_text())
    member_paths = {}
    for node in ast.walk(tm):
        if isinstance(node, ast.ClassDef) and node.name == "ToolEndpoint":
            for item in node.body:
                if isinstance(item, ast.Assign) and len(item.targets) == 1:
                    t = item.targets[0]
                    if isinstance(t, ast.Name) and isinstance(item.value, ast.Constant):
                        member_paths[t.id] = item.value.value

    table = None
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "TOOL_IO":
            table = node.value
    assert table is not None

    specs = []
    for key, value in zip(table.keys, table.values):
        member_name = member(key)  # CBR_TO_PDF
        specs.append((member_paths[member_name], spec_node(value)))

    out = []
    out.append("//! Generated by `scripts/gen_tool_io.py` from")
    out.append("//! `engine/src/stirling/models/tool_io.py` — do not edit by hand.")
    out.append("//! What each tool endpoint accepts/produces; read by")
    out.append("//! `services::tool_io_compat` chain validation.")
    out.append("")
    out.append("use serde::{Deserialize, Serialize};")
    out.append("")
    out.append("use crate::models::tool_models::ToolEndpoint;")
    out.append("")

    def emit_enum(name, values):
        out.append(f"#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]")
        out.append(f"pub enum {name} {{")
        for py_name, py_val in values:
            rust_name = "".join(w.capitalize() for w in py_name.lower().split("_"))
            out.append(f"    #[serde(rename = {rust_str(py_val)})]")
            out.append(f"    {rust_name},")
        out.append("}")
        out.append("")

    emit_enum("ToolFormat", formats)
    emit_enum("ToolArity", arities)

    out.append('#[derive(Debug, Clone, Serialize, Deserialize)]')
    out.append("pub struct ToolIOWhen {")
    out.append("    pub param: String,")
    out.append("    pub matches: Vec<String>,")
    out.append("    #[serde(default, skip_serializing_if = \"Option::is_none\")]")
    out.append("    pub default: Option<String>,")
    out.append("}")
    out.append("")
    out.append('#[derive(Debug, Clone, Serialize, Deserialize)]')
    out.append("pub struct ToolIOCase {")
    out.append("    #[serde(default)]")
    out.append("    pub when: Vec<ToolIOWhen>,")
    out.append("    pub produces: ToolFormat,")
    out.append("    pub arity: ToolArity,")
    out.append("}")
    out.append("")
    out.append('#[derive(Debug, Clone, Serialize, Deserialize)]')
    out.append("pub struct ToolIOSpec {")
    out.append("    pub accepts: Vec<ToolFormat>,")
    out.append("    pub produces: ToolFormat,")
    out.append("    pub arity: ToolArity,")
    out.append("    #[serde(default)]")
    out.append("    pub cases: Vec<ToolIOCase>,")
    out.append("}")
    out.append("")
    out.append("/// `TOOL_IO` lookup; `None` for endpoints that declare nothing.")
    out.append("pub fn tool_io(endpoint: ToolEndpoint) -> Option<ToolIOSpec> {")
    out.append("    Some(match endpoint.as_str() {")

    def fmt_accepts(acc):
        return "vec![" + ", ".join(f"ToolFormat::{a}" for a in acc) + "]"

    for path, spec in specs:
        cases = []
        for c in spec["cases"]:
            whens = []
            for w in c["when"]:
                d = (
                    f", default: Some({rust_str(w['default'])}.to_string())"
                    if w["default"] is not None
                    else ", default: None"
                )
                whens.append(
                    "ToolIOWhen { param: "
                    + rust_str(w["param"])
                    + ".into(), matches: vec!["
                    + ", ".join(rust_str(m) + ".into()" for m in w["matches"])
                    + "]"
                    + d
                    + " }"
                )
            cases.append(
                "ToolIOCase { when: vec!["
                + ", ".join(whens)
                + "], produces: ToolFormat::"
                + c["produces"]
                + ", arity: ToolArity::"
                + c["arity"]
                + " }"
            )
        body = (
            f"ToolIOSpec {{ accepts: {fmt_accepts(spec['accepts'])}, "
            f"produces: ToolFormat::{spec['produces']}, arity: ToolArity::{spec['arity']}, "
            f"cases: vec![{', '.join(cases)}] }}"
        )
        out.append(f"        {rust_str(path)} => {body},")
    out.append("        _ => return None,")
    out.append("    })")
    out.append("}")
    out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(specs)} specs)")


if __name__ == "__main__":
    main()
