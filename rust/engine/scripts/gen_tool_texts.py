#!/usr/bin/env python3
"""Generate src/models/tool_texts.rs — the per-operation retrieval text used
by OperationShortlist ranking.

Reads the checked-in generated Python models (engine/src/stirling/models/
tool_models.py) and reproduces `retrieval_text()` exactly:

    name_words = member_name.lower().replace('_', ' ')
    desc = class docstring (pydantic model_json_schema()['description'])
    params = Field(description=...) per model field, in declaration order
    text = f"{name_words}. {desc} {' '.join(params)}".strip()

Regenerate whenever tool_models.py is regenerated:
    python3 scripts/gen_tool_texts.py
"""

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PY_MODELS = ROOT / "engine/src/stirling/models/tool_models.py"
OUT = ROOT / "rust/engine/src/models/tool_texts.rs"


def field_descriptions(cls: ast.ClassDef) -> list[str]:
    """Field(description=...) strings in declaration order."""
    descs = []
    for node in cls.body:
        if not isinstance(node, ast.AnnAssign):
            continue
        for sub in ast.walk(node.value):
            if (
                isinstance(sub, ast.Call)
                and isinstance(sub.func, ast.Name)
                and sub.func.id == "Field"
            ):
                for kw in sub.keywords:
                    if kw.arg == "description" and isinstance(kw.value, ast.Constant):
                        descs.append(str(kw.value.value).strip())
                break
    return descs


def main() -> None:
    tree = ast.parse(PY_MODELS.read_text())
    classes = {
        node.name: node
        for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef)
    }

    operations = None
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "OPERATIONS"
        ):
            operations = node.value
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "OPERATIONS":
                    operations = node.value
    assert operations is not None, "OPERATIONS dict not found"

    arms = []
    for key, value in zip(operations.keys, operations.values):
        member = key.attr  # e.g. CBR_TO_PDF
        param_cls = value.id
        cls = classes[param_cls]
        doc = ast.get_docstring(cls) or ""
        params = field_descriptions(cls)
        name_words = member.lower().replace("_", " ")
        desc = doc.strip()
        text = f"{name_words}. {desc} {' '.join(params)}".strip()
        arms.append((member, param_cls, text))

    # Member name -> path comes from the ToolEndpoint StrEnum in the same file.
    member_paths = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "ToolEndpoint":
            for item in node.body:
                if isinstance(item, ast.Assign) and len(item.targets) == 1:
                    target = item.targets[0]
                    if isinstance(target, ast.Name) and isinstance(item.value, ast.Constant):
                        member_paths[target.id] = item.value.value

    out = [
        "//! Generated by `scripts/gen_tool_texts.py` from",
        "//! `engine/src/stirling/models/tool_models.py` — do not edit by hand.",
        "//! Retrieval text for `OperationShortlist` ranking; must stay",
        "//! byte-identical to Python's `retrieval_text()`.",
        "",
        "use crate::models::tool_models::ToolEndpoint;",
        "",
        "/// Exact port of `operation_shortlist.retrieval_text`: endpoint name",
        "/// words, model description, then parameter field descriptions.",
        "pub fn retrieval_text(endpoint: ToolEndpoint) -> &'static str {",
        "    match endpoint.as_str() {",
    ]
    for member, _cls, text in arms:
        path = member_paths[member]
        out.append(f"        {json.dumps(path)} => {json.dumps(text)},")
    out += [
        "        _ => \"\",",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(arms)} operations)")


if __name__ == "__main__":
    main()
