//! Regenerate `src/models/tool_params.rs` from the Java OpenAPI spec.
//!
//! Usage (from `rust/engine/`):
//!
//! 1. Fetch the spec from a running Java backend:
//!    `curl -sf http://localhost:8080/v3/api-docs -o /tmp/SwaggerDoc.json`
//! 2. `cargo run --example generate_tool_params -- /tmp/SwaggerDoc.json`
//!
//! This is the Rust counterpart of `engine/scripts/generate_tool_models.py`;
//! the output is checked in so builds never need the Java service.
//!
//! The spec is OpenAPI 3; typify consumes JSON Schema, so each entry under
//! `components.schemas` is fed to the shared TypeSpace — `$ref`s between
//! components resolve inside it.

use std::fmt::Write as _;

fn main() -> anyhow::Result<()> {
    let spec_path = std::env::args()
        .nth(1)
        .ok_or_else(|| anyhow::anyhow!("usage: generate_tool_params <SwaggerDoc.json>"))?;
    let spec_text = std::fs::read_to_string(&spec_path)?;
    let spec: serde_json::Value = serde_json::from_str(&spec_text)?;

    let schemas = spec
        .pointer("/components/schemas")
        .and_then(|s| s.as_object())
        .ok_or_else(|| anyhow::anyhow!("spec has no components.schemas"))?;

    let mut space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
    for (name, schema) in schemas {
        let root: schemars::schema::RootSchema = serde_json::from_value(schema.clone())
            .map_err(|e| anyhow::anyhow!("schema {name}: {e}"))?;
        space
            .add_root_schema(root)
            .map_err(|e| anyhow::anyhow!("schema {name}: {e}"))?;
    }
    let stream = space.to_stream();

    let mut out = String::new();
    writeln!(
        out,
        "//! Generated by `cargo run --example generate_tool_params -- <SwaggerDoc.json>`\n\
         //! from the Java OpenAPI spec (`components.schemas`). Do not edit by hand.\n\
         #![allow(clippy::all, dead_code)]\n"
    )?;
    let file = syn::parse2::<syn::File>(stream)?;
    writeln!(out, "{}", prettyplease::unparse(&file))?;

    let dest = concat!(env!("CARGO_MANIFEST_DIR"), "/src/models/tool_params.rs");
    std::fs::write(dest, out)?;
    println!("wrote {dest}");
    Ok(())
}
