//! Regenerate `src/models/tool_params.rs` from the Java OpenAPI spec.
//!
//! Usage (from `rust/engine/`):
//!
//! 1. Fetch the spec from a running Java backend:
//!    `curl -sf http://localhost:8080/v3/api-docs -o /tmp/SwaggerDoc.json`
//! 2. `cargo run --example generate_tool_params -- /tmp/SwaggerDoc.json`
//!
//! This is the Rust counterpart of `engine/scripts/generate_tool_models.py`;
//! the output is checked in so builds never need the Java service.
//!
//! The spec is OpenAPI 3; typify consumes JSON Schema, so each entry under
//! `components.schemas` is fed to the shared TypeSpace — `$ref`s between
//! components resolve inside it.

use std::fmt::Write as _;

fn main() -> anyhow::Result<()> {
    let spec_path = std::env::args()
        .nth(1)
        .ok_or_else(|| anyhow::anyhow!("usage: generate_tool_params <SwaggerDoc.json>"))?;
    let spec_text = std::fs::read_to_string(&spec_path)?;
    let mut spec: serde_json::Value = serde_json::from_str(&spec_text)?;
    // OpenAPI 3.0 emits boolean `exclusiveMinimum`/`exclusiveMaximum`
    // alongside `minimum`/`maximum`; JSON Schema (and schemars) wants the
    // exclusive bound as a number in place of the inclusive one.
    openapi3_exclusive_bounds(&mut spec);

    let schemas = spec
        .pointer("/components/schemas")
        .and_then(|s| s.as_object())
        .ok_or_else(|| anyhow::anyhow!("spec has no components.schemas"))?;

    // OpenAPI components are not JSON Schema `definitions`: their `$ref`s
    // point at `#/components/schemas/*` and they carry no `title`, which
    // typify requires to emit a named root type. Rewriting the component
    // map into one RootSchema's `definitions` (refs retargeted to
    // `#/definitions/*`) makes every component a named type.
    let mut defs = serde_json::Map::new();
    for (name, schema) in schemas {
        let mut schema = schema.clone();
        retarget_component_refs(&mut schema);
        defs.insert(name.clone(), schema);
    }
    let root_value = serde_json::json!({
        "type": "object",
        "definitions": defs,
    });

    let mut space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
    let root: schemars::schema::RootSchema =
        serde_json::from_value(root_value).map_err(|e| anyhow::anyhow!("combined schema: {e}"))?;
    space
        .add_root_schema(root)
        .map_err(|e| anyhow::anyhow!("combined schema: {e}"))?;
    let stream = space.to_stream();

    let mut out = String::new();
    writeln!(
        out,
        "//! Generated by `cargo run --example generate_tool_params -- <SwaggerDoc.json>`\n\
         //! from the Java OpenAPI spec (`components.schemas`). Do not edit by hand.\n\
         #![allow(clippy::all, dead_code, unused_comparisons)]\n"
    )?;
    let file = syn::parse2::<syn::File>(stream)?;
    writeln!(out, "{}", prettyplease::unparse(&file))?;

    let dest = concat!(env!("CARGO_MANIFEST_DIR"), "/src/models/tool_params.rs");
    std::fs::write(dest, out)?;
    println!("wrote {dest}");
    Ok(())
}

fn retarget_component_refs(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(map) => {
            if let Some(reference) = map.get_mut("$ref").and_then(|v| v.as_str()) {
                if let Some(name) = reference.strip_prefix("#/components/schemas/") {
                    *map.get_mut("$ref").unwrap() =
                        serde_json::Value::String(format!("#/definitions/{name}"));
                }
            }
            for v in map.values_mut() {
                retarget_component_refs(v);
            }
        }
        serde_json::Value::Array(items) => {
            for v in items {
                retarget_component_refs(v);
            }
        }
        _ => {}
    }
}

fn openapi3_exclusive_bounds(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(map) => {
            for key in ["exclusiveMinimum", "exclusiveMaximum"] {
                let Some(bound) = map.get(key).and_then(|v| v.as_bool()) else {
                    continue;
                };
                let inclusive = if key == "exclusiveMinimum" {
                    "minimum"
                } else {
                    "maximum"
                };
                if bound {
                    match map.remove(inclusive) {
                        Some(limit) => {
                            map.insert(key.to_string(), limit);
                        }
                        None => {
                            map.remove(key);
                        }
                    }
                } else {
                    map.remove(key);
                }
            }
            for v in map.values_mut() {
                openapi3_exclusive_bounds(v);
            }
        }
        serde_json::Value::Array(items) => {
            for v in items {
                openapi3_exclusive_bounds(v);
            }
        }
        _ => {}
    }
}
